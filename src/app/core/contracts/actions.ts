/**
 * Actions, events and the shared game vocabulary.
 *
 * Spec: `docs/03-domain-model.md` §§3, 5, 6 and `docs/01-ruleset.md` §§10, 12, 13.
 *
 * **Wire form.** Everything in this file is the *wire* representation: tiles are `TileStr`.
 * The engine's internal action/event types use `TileId` and live in `src/engine/`; the gateway
 * converts between them (resolving a `TileStr` against the player's actual hand, which is why
 * the conversion is context-dependent and cannot live here).
 *
 * This module has ZERO dependencies beyond sibling contract modules.
 */

import type { TileKind, TileStr } from './tiles.js';

// ---------------------------------------------------------------------------
// Seats and winds
// ---------------------------------------------------------------------------

/** Absolute seat, fixed for the whole game. Seat 0 is the starting dealer. */
export type Seat = 0 | 1 | 2 | 3;

/** East, South, West, North. */
export type Wind = 0 | 1 | 2 | 3;

export const SEATS: readonly Seat[] = [0, 1, 2, 3];

export const WIND_EAST: Wind = 0;
export const WIND_SOUTH: Wind = 1;
export const WIND_WEST: Wind = 2;
export const WIND_NORTH: Wind = 3;

export function isSeat(value: unknown): value is Seat {
  return value === 0 || value === 1 || value === 2 || value === 3;
}

/** Seat wind for a hand: `(seat - dealer + 4) % 4`. Absolute seats only. */
export function seatWind(seat: Seat, dealerSeat: Seat): Wind {
  return ((seat - dealerSeat + 4) % 4) as Wind;
}

/** The seat `n` places counter-clockwise from `seat` (1 = shimocha / to your right in turn order). */
export function seatFrom(seat: Seat, offset: number): Seat {
  return ((((seat + offset) % 4) + 4) % 4) as Seat;
}

// ---------------------------------------------------------------------------
// Melds and discards
// ---------------------------------------------------------------------------

export type MeldType = 'chi' | 'pon' | 'daiminkan' | 'shouminkan' | 'ankan';

export const MELD_TYPES = [
  'chi',
  'pon',
  'daiminkan',
  'shouminkan',
  'ankan',
] as const satisfies readonly MeldType[];

/** A meld as it appears on the wire. Melds are always public. */
export interface MeldWire {
  type: MeldType;
  /** 3 tiles for chi/pon, 4 for any kan. */
  tiles: TileStr[];
  /** The tile taken from a discard; `null` for ankan. A shouminkan keeps its original pon call. */
  calledTile: TileStr | null;
  /** Whose discard it came from; `null` for ankan. */
  from: Seat | null;
  /** Index within `tiles` of the called tile — drives rotated-tile rendering. */
  calledIndex: number | null;
}

export interface DiscardWire {
  tile: TileStr;
  /** Discarded immediately after drawing. */
  tsumogiri: boolean;
  /** The riichi declaration discard — rendered rotated. */
  riichiDeclaration: boolean;
  /** Set when someone calls it. Matters for nagashi mangan. */
  calledBy: Seat | null;
}

// ---------------------------------------------------------------------------
// Actions
// ---------------------------------------------------------------------------

/** Server-initiated draw. Never sent by a client. */
export interface DrawAction {
  type: 'draw';
}

/**
 * Discard, optionally declaring riichi. Declaring riichi and choosing the discard is
 * one decision and one action — splitting it creates an invalid intermediate state.
 */
export interface DiscardAction {
  type: 'discard';
  tile: TileStr;
  riichi?: boolean;
}

/** Chi — the two tiles from your own hand. Left player's discard only. */
export interface ChiAction {
  type: 'chi';
  tiles: [TileStr, TileStr];
}

/** Pon — the two tiles from your own hand. */
export interface PonAction {
  type: 'pon';
  tiles: [TileStr, TileStr];
}

/** Open kan on a discard. */
export interface DaiminkanAction {
  type: 'daiminkan';
}

/** Added kan: the 4th tile onto your own pon. Robbable (chankan). */
export interface ShouminkanAction {
  type: 'shouminkan';
  tile: TileStr;
}

/** Concealed kan, from 4 in hand. Keeps the hand closed. */
export interface AnkanAction {
  type: 'ankan';
  kind: TileKind;
}

export interface TsumoAction {
  type: 'tsumo';
}

export interface RonAction {
  type: 'ron';
}

/** Nine-terminals abort, on your first draw with no call having occurred. */
export interface KyuushuAction {
  type: 'kyuushu';
}

/** Decline an open decision window. */
export interface PassAction {
  type: 'pass';
}

/** Timeout / bot-takeover tsumogiri. Generated by the table, never sent by a client. */
export interface AutoDiscardAction {
  type: 'auto-discard';
}

export type Action =
  | DrawAction
  | DiscardAction
  | ChiAction
  | PonAction
  | DaiminkanAction
  | ShouminkanAction
  | AnkanAction
  | TsumoAction
  | RonAction
  | KyuushuAction
  | PassAction
  | AutoDiscardAction;

export type ActionType = Action['type'];

/** Actions a client may originate. `draw` and `auto-discard` are server-side only. */
export type ClientAction = Exclude<Action, DrawAction | AutoDiscardAction>;

export const SERVER_ONLY_ACTION_TYPES: readonly ActionType[] = ['draw', 'auto-discard'];

/**
 * Call priority on a discard: `ron > pon = kan > chi`.
 * Higher wins. Ties between rons are resolved by `docs/01-ruleset.md` §9.
 */
export const CALL_PRIORITY: Readonly<Record<'ron' | 'pon' | 'daiminkan' | 'chi' | 'pass', number>> =
  {
    ron: 3,
    pon: 2,
    daiminkan: 2,
    chi: 1,
    pass: 0,
  };

