  kuitan: boolean;
  /** Swap calling permitted. `false` = forbidden. */
  kuikae: boolean;
  atozuke: boolean;
  agariYame: boolean;
  /** Bust ends the game. */
  tobi: boolean;
  enchousen: boolean;
  nagashiMangan: boolean;
  /** Triple ron aborts instead. */
  doubleRon: boolean;
  sanchahouAborts: boolean;
  /** Pao + daiminkan rinshan liability. */
  sekininBarai: boolean;
