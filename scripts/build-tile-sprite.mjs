/**
 * Assemble the vendored tile art into one sprite sheet.
 *
 *   npm run build:tiles           write public/tiles/traditional.svg
 *   npm run build:tiles -- --check  fail if it is stale (CI)
 *
 * `docs/08-graphics-ux.md` §3: *"one SVG sprite sheet per face set, `<symbol id="t-5m">…`,
 * referenced via `<use>`. Vector so it scales to any DPI; a single request."* This produces that
 * single request from the 38 files in `vendor/riichi-mahjong-tiles/`.
 *
 * Three things it has to do, and the middle one is the one that bites:
 *
 * 1. **Optimise.** The vendored files are Inkscape output — 800 kB of editor metadata, namespaces
 *    and comments around the actual geometry. svgo takes that to ~290 kB, which gzips to ~21 kB.
 * 2. **Prefix every id.** All 38 files came out of the same editor and reuse ids: `defs4`,
 *    `linearGradient4`, `path12`. Concatenating them into one document silently cross-wires the
 *    gradient fills and `<use>` references — the pin tiles are drawn almost entirely from `<use>`,
 *    so a collision does not error, it just draws the wrong tile. svgo's `prefixIds` namespaces
 *    them per file.
 * 3. **Keep the viewBox and drop width/height**, so each `<symbol>` scales to whatever box the tile
 *    component gives it.
 *
 * The output is committed, and `--check` holds it to the vendored input the way the contract and
 * fixture checks do: a generated file that can drift from its source is a generated file nobody
 * can trust.
 */

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { optimize } from 'svgo';

const repoRoot = fileURLToPath(new URL('..', import.meta.url));
const VENDOR = join(repoRoot, 'vendor', 'riichi-mahjong-tiles');
const OUT_DIR = join(repoRoot, 'public', 'tiles');
const OUT_FILE = join(OUT_DIR, 'traditional.svg');

/**
 * Upstream filename → wire tile.
 *
 * `Ton`/`Nan`/`Shaa`/`Pei` are the winds in seat order and `Haku`/`Hatsu`/`Chun` the dragons, which
 * is `1z`–`7z`. `*5-Dora` is the red five, which the wire calls `0m`/`0p`/`0s`.
 */
const FACES = {
  Man1: '1m',
  Man2: '2m',
  Man3: '3m',
  Man4: '4m',
  Man5: '5m',
  Man6: '6m',
  Man7: '7m',
  Man8: '8m',
  Man9: '9m',
  'Man5-Dora': '0m',
  Pin1: '1p',
  Pin2: '2p',
  Pin3: '3p',
  Pin4: '4p',
  Pin5: '5p',
  Pin6: '6p',
  Pin7: '7p',
  Pin8: '8p',
  Pin9: '9p',
  'Pin5-Dora': '0p',
  Sou1: '1s',
  Sou2: '2s',
  Sou3: '3s',
  Sou4: '4s',
  Sou5: '5s',
  Sou6: '6s',
  Sou7: '7s',
  Sou8: '8s',
  Sou9: '9s',
  'Sou5-Dora': '0s',
  Ton: '1z',
  Nan: '2z',
  Shaa: '3z',
  Pei: '4z',
  Haku: '5z',
  Hatsu: '6z',
  Chun: '7z',
};

/** The face-down tile. Not a `TileStr`, so it gets its own id. */
const BACK_FILE = 'Back';

/** Must match `faceSymbolId()` / `BACK_SYMBOL_ID` in `shared/tiles/tile-faces.ts`. */
const PREFIX = 'mj-tr-';
const BACK_SYMBOL_ID = 'mj-tr-back';

/**
 * 0.01 of a 300-unit viewBox is 0.0015 px at hand size. Two decimals is already far below anything
 * a screen can show; the saving over three is 15% of the download.
 */
const FLOAT_PRECISION = 2;

function symbolFor(file, symbolId) {
  const path = join(VENDOR, `${file}.svg`);
  if (!existsSync(path)) throw new Error(`missing vendored tile: ${path}`);

  const { data } = optimize(readFileSync(path, 'utf8'), {
    multipass: true,
    floatPrecision: FLOAT_PRECISION,
    plugins: [
      { name: 'preset-default' },
      // Namespaced per source file, which is what stops 38 Inkscape documents cross-wiring.
      { name: 'prefixIds', params: { prefix: file, delim: '-' } },
      { name: 'removeDimensions' },
      { name: 'removeXMLNS' },
    ],
  });

  const viewBox = /viewBox="([^"]+)"/.exec(data)?.[1];
  if (viewBox === undefined) throw new Error(`${file}.svg has no viewBox`);

  const inner = data.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  return `<symbol id="${symbolId}" viewBox="${viewBox}">${inner}</symbol>`;
}

function build() {
  const symbols = Object.entries(FACES).map(([file, tile]) => symbolFor(file, `${PREFIX}${tile}`));
  symbols.push(symbolFor(BACK_FILE, BACK_SYMBOL_ID));

  const banner =
    '<!-- GENERATED by `npm run build:tiles` from vendor/riichi-mahjong-tiles/ (CC0). ' +
    'Do not edit; see frontend/ASSETS.md. -->';

  return `<svg xmlns="http://www.w3.org/2000/svg">${banner}${symbols.join('')}</svg>\n`;
}

function main() {
  const check = process.argv.includes('--check');
  const sprite = build();

  if (check) {
    if (!existsSync(OUT_FILE)) {
      console.error('public/tiles/traditional.svg is missing; run `npm run build:tiles`');
      process.exit(1);
    }
    const current = readFileSync(OUT_FILE, 'utf8');
    if (current !== sprite) {
      const hash = (value) => createHash('sha256').update(value).digest('hex').slice(0, 12);
      console.error(
        `public/tiles/traditional.svg is stale (has ${hash(current)}, want ${hash(sprite)})`,
      );
      console.error('run `npm run build:tiles` and commit the result');
      process.exit(1);
    }
    console.log(`tile sprite is up to date (${String(Object.keys(FACES).length + 1)} symbols)`);
    return;
  }

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(OUT_FILE, sprite, 'utf8');
  console.log(
    `wrote public/tiles/traditional.svg — ${String(Object.keys(FACES).length + 1)} symbols, ` +
      `${String(Math.round(sprite.length / 1024))} kB`,
  );
}

main();
