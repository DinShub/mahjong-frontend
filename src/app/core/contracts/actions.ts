export interface AgariResult {
  seat: Seat;
  /** The discarder; `=== seat` for tsumo. */
  from: Seat;
  hand: TileStr[];
  melds: MeldWire[];
  winningTile: TileStr;
  yaku: YakuValue[];
  yakuman: YakuId[];
  dora: number;
  uraDora: number;
  redDora: number;
  han: number;
  fu: number;
  /** Total gained, including honba and riichi sticks. */
  points: number;
  /** Per-seat; sums to 0 across all winners of the hand. */
  scoreDeltas: number[];
  limitName: LimitName | null;
}

/**
 * `exhaustive` plus the five abortive draws of `docs/01-ruleset.md` §8.
 * Nagashi mangan is an *exhaustive* draw with a different payment, reported via
 * `RyuukyokuEvent.nagashi`.
 */
export type RyuukyokuReason =
  'exhaustive' | 'kyuushu_kyuuhai' | 'suufon_renda' | 'suucha_riichi' | 'suukaikan' | 'sanchahou';

export interface Placement {
  seat: Seat;
  /** 1…4. Ties broken by seat order from the starting dealer; no split placements. */
  place: 1 | 2 | 3 | 4;
  finalScore: number;
  /** After uma + oka, in units of 1000. */
  netScore: number;
}

export type BotLevel = 'easy' | 'normal' | 'hard';

export interface PlayerInfo {
  /** `null` for a pure bot seat. */
  userId: string | null;
  displayName: string;
  avatarId: string;
  isBot: boolean;
  botLevel: BotLevel | null;
}

