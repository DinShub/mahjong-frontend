/**
 * The engine's output and the only thing persisted or sent to clients: state is `fold(events)`.
 * Every event is projected per recipient before it leaves the server — see `projectFor()`
 * and the redaction table in `docs/03-domain-model.md` §6.
 */
export interface GameStartEvent {
  t: 'game-start';
  config: RuleConfig;
  players: PlayerInfo[];
  /** sha256 of the seed, published at game start so the wall can be verified afterwards. */
  seedHash: string;
  /** Withheld from clients until `game-end`. */
  seed?: string;
}

export interface HandStartEvent {
  t: 'hand-start';
  handIndex: number;
  round: Wind;
  kyoku: number;
  honba: number;
  riichiSticks: number;
  dealer: Seat;
  scores: number[];
  /** Index === seat. The real 13 tiles for the viewer, `null` for everyone else. */
  hands: (TileStr[] | null)[];
  doraIndicator: TileStr;
}

export interface DrawEvent {
  t: 'draw';
  seat: Seat;
  /** Present only for the drawer. */
  tile: TileStr | null;
  fromRinshan: boolean;
  wallRemaining: number;
}

export interface DiscardEvent {
  t: 'discard';
  seat: Seat;
  tile: TileStr;
  tsumogiri: boolean;
  riichi: boolean;
}

export interface CallEvent {
  t: 'call';
  seat: Seat;
  meld: MeldWire;
  from: Seat;
}

export interface RiichiAcceptedEvent {
  t: 'riichi-accepted';
  seat: Seat;
  /** Sticks on the table after the deposit. */
  sticks: number;
  scores: number[];
}

export interface DoraRevealedEvent {
  t: 'dora-revealed';
  indicator: TileStr;
}

export interface AgariEvent {
  t: 'agari';
  winners: AgariResult[];
  scores: number[];
  scoreDeltas: number[];
  /** Revealed only when a riichi hand won. */
  uraIndicators?: TileStr[];
}

export interface RyuukyokuEvent {
  t: 'ryuukyoku';
  reason: RyuukyokuReason;
  /** Index === seat; meaningful for `exhaustive` only. */
  tenpai: boolean[];
  /** Revealed hands at an exhaustive draw; `null` where not revealed. */
  hands: (TileStr[] | null)[];
  scores: number[];
  scoreDeltas: number[];
  /** Seats scoring nagashi mangan, if any. */
  nagashi?: Seat[];
}

export interface HandEndEvent {
  t: 'hand-end';
  nextDealer: Seat;
  nextHonba: number;
  /** Sticks carried over to the next hand. */
  riichiSticks: number;
}

export interface GameEndEvent {
  t: 'game-end';
  placements: Placement[];
  /** Released here so any client can re-derive the walls and verify them against `seedHash`. */
  seed: string;
}

export type GameEvent =
  | GameStartEvent
  | HandStartEvent
  | DrawEvent
  | DiscardEvent
  | CallEvent
  | RiichiAcceptedEvent
  | DoraRevealedEvent
  | AgariEvent
  | RyuukyokuEvent
  | HandEndEvent
  | GameEndEvent;

export type GameEventType = GameEvent['t'];
